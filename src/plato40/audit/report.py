"""Assemble the data audit report from its sections and write it to disk."""

from __future__ import annotations

import platform
from importlib.metadata import version

from plato40.audit import (
    baselines,
    implications,
    integrity,
    inventory,
    quality,
    scenarios,
    seasonality,
    timing,
)
from plato40.load.reader import Dataset
from plato40.settings import Settings

REPORT_NAME = "01_data_audit.md"


def header(datasets: list[Dataset]) -> str:
    """Return the report title, provenance and reading guide."""
    names = ", ".join(f"`{ds.path.name}` ({ds.profile})" for ds in datasets)
    return "\n".join(
        [
            "# PLATO-40 data audit",
            "",
            "Generated by `make audit DATA=<data_root>` (`plato40 audit <data_root> "
            "--out reports/audit`). Do not edit by hand: every number below is computed "
            "by `src/plato40/audit/`. Rerunning on the same data reproduces this file "
            "and its figures byte for byte.",
            "",
            f"Datasets: {names}. They are independent synthetic runs and are analysed "
            "separately, never concatenated. Python "
            f"{platform.python_version()}, pandas {version('pandas')}, "
            f"numpy {version('numpy')}, matplotlib {version('matplotlib')}.",
            "",
            "Conventions: times are UTC unless marked local (Europe/Vienna). Blank fields "
            "are missing, never zero. Episodes named here are *candidates* found by "
            "screening rules, not detections. Each subsection states its hypothesis first, "
            "then what the data shows.",
            "",
        ]
    )


def build(datasets: list[Dataset], settings: Settings) -> str:
    """Return the full report markdown."""
    sections = [
        header(datasets),
        inventory.render(datasets),
        quality.render(datasets, settings),
        integrity.render(datasets),
        timing.render(datasets, settings),
        scenarios.render(datasets, settings),
        baselines.render(datasets, settings),
        seasonality.render(datasets, settings),
        implications.render(datasets, settings),
    ]
    return "\n".join(sections).rstrip() + "\n"


def write(datasets: list[Dataset], settings: Settings) -> None:
    """Build the report and write it to ``settings.out_dir``."""
    settings.out_dir.mkdir(parents=True, exist_ok=True)
    text = build(datasets, settings)
    (settings.out_dir / REPORT_NAME).write_text(text, encoding="utf-8")
